#!/usr/bin/env python3
"""Write Sources/DeviceConverter/ProCTables.swift from the calibration measurements.

    gen_tables.py <measurements dir> <out.swift>

Reads, from the measurements dir (see README.md for how each is made):
  timing_map.json          fit_timing.py: Pro-C 2 attack/release (ms) per Pro-C timing setting
  c1_autogain_table.json   Pro-C's Auto Gain makeup by style, knee, threshold and ratio
  c1_autogain_attack.json  how that makeup shrinks with attack
  link_map.json            Pro-C side-chain mix spread → Pro-C 2 stereo link %
  FC2p_release.txt         Pro-C 2's release scale (auhost strings, 101 points)
"""
import json, os, sys

src, out = sys.argv[1], sys.argv[2]
J = lambda n: json.load(open(os.path.join(src, n)))
timing, makeup, attack_factor, link = J('timing_map.json'), J('c1_autogain_table.json'), \
    J('c1_autogain_attack.json'), J('link_map.json')
release = []
for line in open(os.path.join(src, 'FC2p_release.txt')):
    x, text = line.split('\t')
    v, unit = text.split()[:2]
    release.append((float(x), float(v) * (1000 if unit.startswith('sec') else 1)))


def arr(xs, fmt='{:.6g}'):
    return '[' + ', '.join(fmt.format(x) for x in xs) + ']'


def grid(g):  # [style][a][b] -> [[attackMs, releaseMs, null]] → flat per style
    return '[\n' + ',\n'.join(
        '    ' + arr([v for row in g[str(st)] for cell in row for v in cell[:2]]) for st in range(3)) + ',\n  ]'


swift = f'''// Generated by Calibration/ProCToProC2/gen_tables.py. Don't edit by hand.
import Foundation

/// FabFilter Pro-C → Pro-C 2 calibration, measured by rendering both plugins
/// offline (see Calibration/ProCToProC2/README.md).
enum ProCTables {{
  // MARK: Timing

  /// Pro-C attack settings (0–1) the timing grids are measured at.
  static let attackGrid: [Double] = {arr(timing['x'])}
  /// Pro-C release settings (0–1), with auto release off.
  static let releaseGrid: [Double] = {arr(timing['rx'])}
  /// Pro-C auto release speeds (0–1), with auto release on.
  static let speedGrid: [Double] = {arr(timing['speeds'])}

  /// Per style: the Pro-C 2 attack and release (ms) that sound closest, for each
  /// attack × release setting, flattened as [attack, release] pairs.
  static let manual: [[Double]] = {grid(timing['manual'])}
  /// The same with auto release on, for each attack × speed setting.
  static let auto: [[Double]] = {grid(timing['auto'])}

  static func manualTiming(style: Int, attack: Double, release: Double) -> (attackMs: Double, releaseMs: Double) {{
    lookup(manual[clampStyle(style)], attack, release, releaseGrid)
  }}

  static func autoTiming(style: Int, attack: Double, speed: Double) -> (attackMs: Double, releaseMs: Double) {{
    lookup(auto[clampStyle(style)], attack, speed, speedGrid)
  }}

  /// Bilinear in log milliseconds.
  private static func lookup(_ flat: [Double], _ a: Double, _ b: Double, _ bGrid: [Double])
    -> (attackMs: Double, releaseMs: Double)
  {{
    let (i, fi) = cell(attackGrid, a), (j, fj) = cell(bGrid, b)
    func at(_ i: Int, _ j: Int, _ k: Int) -> Double {{ log(flat[(i * bGrid.count + j) * 2 + k]) }}
    func value(_ k: Int) -> Double {{
      let low = at(i, j, k) * (1 - fj) + at(i, j + 1, k) * fj
      let high = at(i + 1, j, k) * (1 - fj) + at(i + 1, j + 1, k) * fj
      return exp(low * (1 - fi) + high * fi)
    }}
    return (value(0), value(1))
  }}

  // MARK: Auto gain

  static let makeupThresholds: [Double] = {arr(makeup['thresholds'])}
  static let makeupRatios: [Double] = {arr(makeup['ratios'])}
  /// dB, by style × knee (soft, hard), then threshold × ratio, flattened.
  static let makeup: [[Double]] = [
{chr(10).join('    ' + arr([v for row in makeup['makeup'][f'{st}{kn}'] for v in row], '{:.3f}') + ',' for st in range(3) for kn in range(2))}
  ]
  static let makeupAttack: [Double] = {arr(attack_factor['attack'])}
  static let makeupAttackFactor: [Double] = {arr(attack_factor['factor'], '{:.4f}')}

  /// Pro-C's Auto Gain makeup in dB. It shrinks for slow attacks, to none from 0.9.
  static func makeupDb(style: Int, hardKnee: Bool, threshold: Double, ratio: Double, attack: Double) -> Double {{
    let table = makeup[clampStyle(style) * 2 + (hardKnee ? 1 : 0)]
    let (i, fi) = cell(makeupThresholds, threshold), (j, fj) = cell(makeupRatios, ratio)
    func at(_ i: Int, _ j: Int) -> Double {{ table[i * makeupRatios.count + j] }}
    let low = at(i, j) * (1 - fj) + at(i, j + 1) * fj
    let high = at(i + 1, j) * (1 - fj) + at(i + 1, j + 1) * fj
    return (low * (1 - fi) + high * fi) * interpolate(makeupAttack, makeupAttackFactor, attack)
  }}

  // MARK: Stereo link

  /// How far apart Pro-C's two side-chain mixes are (0: both hear the sum, 1: each
  /// hears its own side) → Pro-C 2's stereo link in percent.
  static let linkSpread: [Double] = {arr([r[0] for r in link])}
  static let linkPercents: [Double] = {arr([r[1] for r in link])}

  static func linkPercent(spread: Double) -> Double {{ interpolate(linkSpread, linkPercents, spread) }}

  // MARK: Pro-C 2's scales

  /// Pro-C 2's attack: 0.005 + 250·x³ ms.
  static func proC2Attack(ms: Double) -> Double {{ min(1, max(0, cbrt((ms - 0.005) / 250))) }}

  static let releaseX: [Double] = {arr([r[0] for r in release])}
  static let releaseMs: [Double] = {arr([r[1] for r in release], '{:.5g}')}

  /// Pro-C 2's release setting for a time, from its own display scale (log ms).
  static func proC2Release(ms: Double) -> Double {{
    interpolate(releaseMs.map(log), releaseX, log(min(max(ms, releaseMs[0]), releaseMs[releaseMs.count - 1])))
  }}

  // MARK: Helpers

  private static func clampStyle(_ s: Int) -> Int {{ min(max(s, 0), 2) }}

  /// The grid cell holding `x` (clamped), and how far along it is.
  private static func cell(_ grid: [Double], _ x: Double) -> (Int, Double) {{
    let x = min(max(x, grid[0]), grid[grid.count - 1])
    var i = 0
    while i < grid.count - 2 && x > grid[i + 1] {{ i += 1 }}
    return (i, (x - grid[i]) / (grid[i + 1] - grid[i]))
  }}

  private static func interpolate(_ xs: [Double], _ ys: [Double], _ x: Double) -> Double {{
    let (i, f) = cell(xs, x)
    return ys[i] * (1 - f) + ys[i + 1] * f
  }}
}}
'''
open(out, 'w').write(swift)
print(f'wrote {out}')
